function sigs = can_protocol_def()
%CAN_PROTOCOL_DEF  示例 CAN 协议：ID 0x18F  BMS_Status  DLC = 8（纯 Intel / 小端）
%
%   字段说明（与 Vector DBC 语义完全一致）：
%     startBit  起始位 0~63
%                 Intel -> 该信号【最低位 LSB】所在位置（也就等于左移位数）
%     length    位宽（1~63）
%     order     'Intel'
%     signed    true = 二进制补码有符号
%     scale     物理值 = raw * scale + offset
%     offset
%     min/max   物理范围，仅用于检查/显示
%
%   位分配（Byte0..Byte7，每字节 bit7..bit0，正好 64 位无空隙）：
%
%     Byte0 : [ PackVoltage bits 7:0 ....................... ]   0x92
%     Byte1 : [ PackCurrent bits 3:0 ][ PackVoltage bits 11:8 ]  0x7F
%     Byte2 : [ PackCurrent bits 11:4 ..................... ]   0xB1
%     Byte3 : [ SOC ....................................... ]   0xBF
%     Byte4 : [ CellTempMax ............................... ]   0x22
%     Byte5 : [ CellVoltMax bits 7:0  （低字节！）......... ]   0x44
%     Byte6 : [ CellVoltMax bits 15:8 （高字节！）......... ]   0x0E
%     Byte7 : [ BalanceState 4b ][ ThermalMode 3b ][ ChargeFlag 1b ] 0x57
%
%   三个跨字节 Intel 信号，覆盖最容易错的三种情形：
%     1. PackVoltage : 12 bit，跨 Byte0 -> Byte1 低半字节
%     2. PackCurrent : 12 bit，跨 Byte1 高半字节 -> Byte2 整字节
%     3. CellVoltMax : 16 bit，跨 Byte5/Byte6，且【低字节在前、高字节在后】
%
%   注意 Byte1：低半字节属于 PackVoltage，高半字节属于 PackCurrent，
%   同一个字节被两个不同信号从两端分别占用，是最典型的踩坑点。

sigs(1) = struct( ...
    'name','PackVoltage', 'startBit',0,  'length',12, ...
    'order','Intel',    'signed',false, 'scale',0.1, 'offset',0, ...
    'min',0, 'max',409.5, 'unit','V', ...
    'comment','跨 Byte0 全部 + Byte1 低 4 位');

sigs(2) = struct( ...
    'name','PackCurrent', 'startBit',12, 'length',12, ...
    'order','Intel',    'signed',true,  'scale',0.1, 'offset',0, ...
    'min',-204.8, 'max',204.7, 'unit','A', ...
    'comment','LSB 在 Byte1.bit4，跨 Byte1 高 4 位 + Byte2');

sigs(3) = struct( ...
    'name','SOC', 'startBit',24, 'length',8, ...
    'order','Intel',    'signed',false, 'scale',0.4, 'offset',0, ...
    'min',0, 'max',102, 'unit','%', ...
    'comment','Byte3 整字节');

sigs(4) = struct( ...
    'name','CellTempMax', 'startBit',32, 'length',8, ...
    'order','Intel',    'signed',true,  'scale',1, 'offset',0, ...
    'min',-128, 'max',127, 'unit','degC', ...
    'comment','Byte4 整字节，有符号');

sigs(5) = struct( ...
    'name','CellVoltMax', 'startBit',40, 'length',16, ...
    'order','Intel',    'signed',false, 'scale',0.001, 'offset',0, ...
    'min',0, 'max',65.535, 'unit','V', ...
    'comment','低字节在 Byte5，高字节在 Byte6（小端字节序）');

sigs(6) = struct( ...
    'name','ChargeFlag', 'startBit',56, 'length',1, ...
    'order','Intel',    'signed',false, 'scale',1, 'offset',0, ...
    'min',0, 'max',1, 'unit','', ...
    'comment','Byte7.bit0');

sigs(7) = struct( ...
    'name','ThermalMode', 'startBit',57, 'length',3, ...
    'order','Intel',    'signed',false, 'scale',1, 'offset',0, ...
    'min',0, 'max',7, 'unit','', ...
    'comment','Byte7.bit3..bit1');

sigs(8) = struct( ...
    'name','BalanceState', 'startBit',60, 'length',4, ...
    'order','Intel',    'signed',false, 'scale',1, 'offset',0, ...
    'min',0, 'max',15, 'unit','', ...
    'comment','Byte7.bit7..bit4');

end
